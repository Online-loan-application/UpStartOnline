-- Set the third serial's display text to the Transaction Reference Code explanation.
-- Run after transfer_demo_serials.sql.

create or replace function public.set_third_transaction_reference_code_display()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.sequence = 3 then
    new.name := 'Transaction Reference Code (TRC)';
    new.description := 'A unique combination of letters and numbers generated by the online banking system when a user initiates a bank transfer. The code serves as a transaction identifier, allowing the user to track, verify, and reference the payment. If a transaction requires a reference code, it is generated by the bank or payment provider and is not purchased separately.';
  end if;
  return new;
end;
$$;

revoke all on function public.set_third_transaction_reference_code_display() from public, anon, authenticated;

drop trigger if exists set_third_transaction_reference_code_display on public.transfer_demo_serials;
create trigger set_third_transaction_reference_code_display
  before insert or update of sequence, name, description on public.transfer_demo_serials
  for each row execute function public.set_third_transaction_reference_code_display();

update public.transfer_demo_serials
  set name = 'Transaction Reference Code (TRC)',
      description = 'A unique combination of letters and numbers generated by the online banking system when a user initiates a bank transfer. The code serves as a transaction identifier, allowing the user to track, verify, and reference the payment. If a transaction requires a reference code, it is generated by the bank or payment provider and is not purchased separately.'
  where sequence = 3;
